export async function exportEventDataJSON(
  eventName: string,
  eventData: Record<string, any>,
  user: UserProfile
) {
  const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(eventData, null, 2));
  const downloadAnchor = document.createElement("a");
  downloadAnchor.setAttribute("href", dataStr);
  downloadAnchor.setAttribute("download", `${eventName.replace(/\s+/g, "_")}_backup_${new Date().toISOString().slice(0, 10)}.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();

  await logAudit({
    userId: user.uid,
    userRole: user.role,
    userName: user.name,
    action: "export_event_json_backup",
    category: "report_export",
    description: `Exported event data JSON backup for "${eventName}"`,
  });
}
