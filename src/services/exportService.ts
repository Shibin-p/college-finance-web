import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { formatINR, formatDateTime } from "../utils/formatters";
import { logAudit } from "./auditService";
import type { UserProfile, YearWiseStatsModel } from "../types";

export interface ClassReportRow {
  class: string;
  department: string;
  year: number;
  totalStudents: number;
  fullyPaid: number;
  partiallyPaid: number;
  pending: number;
  exempted: number;
  totalRequired: number;
  totalReceived: number;
  totalOutstanding: number;
  collectionPercentage: string;
}

export async function exportClassReportExcel(
  eventName: string,
  data: ClassReportRow[],
  user: UserProfile
) {
  const wsData = [
    [`EKCTC Finance - Class-wise Collection Report`],
    [`Event: ${eventName}`],
    [`Generated by: ${user.name} (${user.role}) on ${formatDateTime(new Date())}`],
    [],
    [
      "Class",
      "Department",
      "Year",
      "Total Students",
      "Fully Paid",
      "Partially Paid",
      "Pending",
      "Exempted",
      "Required (INR)",
      "Received (INR)",
      "Outstanding (INR)",
      "Collection %",
    ],
    ...data.map((r) => [
      r.class,
      r.department,
      r.year,
      r.totalStudents,
      r.fullyPaid,
      r.partiallyPaid,
      r.pending,
      r.exempted,
      r.totalRequired,
      r.totalReceived,
      r.totalOutstanding,
      r.collectionPercentage,
    ]),
  ];

  const ws = XLSX.utils.aoa_to_sheet(wsData);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Class Report");
  XLSX.writeFile(wb, `${eventName.replace(/\s+/g, "_")}_Class_Report.xlsx`);

  await logAudit({
    userId: user.uid,
    userRole: user.role,
    userName: user.name,
    action: "export_excel_class_report",
    category: "report_export",
    description: `Exported Excel class report for event "${eventName}"`,
  });
}

export async function exportClassReportPDF(
  eventName: string,
  data: ClassReportRow[],
  user: UserProfile
) {
  const doc = new jsPDF({ orientation: "landscape" });

  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text("EKCTC Finance - Class Collection Report", 14, 15);

  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(`Event: ${eventName} | Generated by: ${user.name} | ${formatDateTime(new Date())}`, 14, 22);

  const tableRows = data.map((r) => [
    r.class,
    r.department,
    r.year.toString(),
    r.totalStudents.toString(),
    r.fullyPaid.toString(),
    r.partiallyPaid.toString(),
    r.pending.toString(),
    r.exempted.toString(),
    formatINR(r.totalRequired),
    formatINR(r.totalReceived),
    formatINR(r.totalOutstanding),
    r.collectionPercentage,
  ]);

  autoTable(doc, {
    startY: 28,
    head: [[
      "Class",
      "Dept",
      "Yr",
      "Total",
      "Full",
      "Part",
      "Pend",
      "Exempt",
      "Required",
      "Received",
      "Outstanding",
      "%",
    ]],
    body: tableRows,
    theme: "grid",
    headStyles: { fillColor: [15, 23, 42], textColor: 255, fontStyle: "bold" },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    styles: { fontSize: 8, cellPadding: 3 },
  });

  doc.save(`${eventName.replace(/\s+/g, "_")}_Class_Report.pdf`);

  await logAudit({
    userId: user.uid,
    userRole: user.role,
    userName: user.name,
    action: "export_pdf_class_report",
    category: "report_export",
    description: `Exported PDF class report for event "${eventName}"`,
  });
}

